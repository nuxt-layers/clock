// Regenerates shared/time-zones.ts from an IANA tzdata.zi file (primary `Z` zones only).
// Usage: node scripts/generate-time-zones.mjs [/usr/share/zoneinfo/tzdata.zi]
import { readFileSync, writeFileSync } from 'node:fs'
const source = readFileSync(process.argv[2] ?? '/usr/share/zoneinfo/tzdata.zi', 'utf8')
const version = /^# version (\S+)/m.exec(source)?.[1] ?? 'unknown'
const names = [...source.matchAll(/^Z (\S+)/gm)].map(m => m[1])
  .filter(name => name.includes('/') && !name.startsWith('Etc/'))
const zones = [...new Set([...names, 'UTC'])].sort()
writeFileSync(new URL('../shared/time-zones.ts', import.meta.url),
  `// Generated by scripts/generate-time-zones.mjs from IANA tzdata ${version}: primary Area/Location zones plus UTC.\n` +
  `// Do not edit by hand.\nexport const tzdataVersion = '${version}'\nexport const ianaZones: readonly string[] = ${JSON.stringify(zones, null, 0).replace(/","/g, "', '").replace('["', "['").replace('"]', "']")}\n`)
console.log(`${zones.length} zones from tzdata ${version}`)
